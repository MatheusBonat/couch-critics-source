const dictionaries: Record<Lang, Dictionary> = { pt, en };

const storageKey = "notas-lang";

// A escolha fica salva no aparelho. Se o armazenamento não estiver disponível, o app segue funcionando.
function readSavedLang(): Lang | null {
  try {
    const saved = localStorage.getItem(storageKey);
    return saved === "pt" || saved === "en" ? saved : null;
  } catch {
    return null;
  }
}

// Sem escolha salva, segue o idioma do sistema: português para quem usa português, inglês para os demais.
function detectLang(): Lang {
  return navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Dictionary;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readSavedLang() ?? detectLang());

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(storageKey, next);
    } catch {
      // Sem armazenamento: a escolha vale só até fechar o app.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t: dictionaries[lang] }), [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n precisa estar dentro de <I18nProvider>.");
  return value;
}
